/** Reference parameter provenance. Generation uses the new module contracts and implementations. */
export function neo75hParameterOwner(path) {
  if (!Object.hasOwn(SOURCE_PARAMETERS, path)) return null;
  if (path === 'bkp') return 'app-params';
  if (path.startsWith('sw.cali.')) return 'app-calibration';
  if (path.startsWith('sw.safety.')) return 'app-safety';
  if (path.startsWith('sw.obs.')) return 'foc-observer';
  if (path.startsWith('sw.ctrl.friction.')) return 'foc-compensation';
  if (path.startsWith('sw.sensor.') || ['mech.motor.npp', 'sw.ctrl.elec_theta_source', 'sw.ctrl.dir', 'sw.ctrl.pwm_elec_theta_delay_comp_cycle', 'hw.cur_sample.reconstruct_phase'].includes(path)) return 'foc-feedback';
  if (['hw.timer.pwm_duty_min', 'hw.timer.pwm_duty_max'].includes(path)) return 'foc-modulation';
  if (path.startsWith('hw.comm.')) return 'app-comms';
  if (path.startsWith('hw.timer.') || /^(hw\.(cur_sample|volt_sample|ntc)\.adc\.)/.test(path)) return 'hw-board';
  if (path.startsWith('hw.encoder.') || path.startsWith('hw.tor_sensor.') || path.startsWith('hw.ntc.') || path.startsWith('mech.ntc.')) return 'hw-sensors';
  if (['hw.volt_sample.bus_volt_max', 'hw.volt_sample.bus_volt_min', 'hw.volt_sample.power_off_bus_volt_min'].includes(path)) return 'app-safety';
  if (path.startsWith('hw.')) return 'hw-board';
  if (['mech.motor.ld', 'mech.motor.lq', 'mech.motor.rs', 'mech.motor.psi', 'mech.motor.cur_rated', 'mech.motor.cur_peak', 'sw.ctrl.cur_ctrl', 'sw.ctrl.cur_loop_bandwidth', 'sw.ctrl.fw_v_bus_ratio', 'sw.ctrl.freq_div.fw'].includes(path) || /^sw\.ctrl\.(id_pi|iq_pi|id_adrc|iq_adrc|fw_pi)\./.test(path)) return 'foc-current';
  if (['mech.motor.warn_temp_max', 'mech.motor.fault_temp_max'].includes(path)) return 'app-safety';
  return 'app-motion';
}

export function getNeo75hModuleMap(variant = 'KW') {
  const profile = getNeo75hProfile(variant);
  return MODULES.map(module => {
    const name=module.contracts.input.name.replace(/Input$/,'').toLowerCase();
    const layer={hardware:'hardware',foc:'algorithm',app:'application'}[module.layer];
    return {
      moduleId:module.id,layer:module.layer,
      parameterPaths:Object.keys(profile.sourceParameters).filter(path=>neo75hParameterOwner(path)===module.id),
      resourceBinding:{configObject:module.contracts.state.name,fields:module.contracts.state.fields.map(field=>field.name),source:`firmware/${layer}/${name}/${name}.c`,entryPoints:[`${name}_step`]},
    };
  });
}

function memoryPlan(target) {
  const plan = createMemoryPlan(target);
  plan.layout.banks = [1, 2].map(number => ({
    id: `neo-bank-${number}`, name: `Bank ${number}`, baseAddress: number === 1 ? 0x08000000 : 0x08100000, sizeKiB: 1024, executable: true,
    sectors: Array.from({ length: 8 }, (_, index) => ({
      id: `neo-bank-${number}-sector-${index}`, offsetKiB: index * 128, sizeKiB: 128,
      name: `Sector ${index}${number === 1 ? [' · 硬件层', ' · 算法层', ' · 应用层', '', '', '', '', ''][index] : index < 4 ? ' · M4 通信' : ['', '', '', '', '', ' · 校准', ' · 参数', ' · 日志'][index]}`,
      reserved: number === 2 && index < 4,
    })),
  }));
  for (const [id, bank, sector] of [['hardware', 1, 0], ['foc', 1, 1], ['app', 1, 2], ['motion-calibration', 2, 5], ['parameters', 2, 6], ['fault-records', 2, 7]]) {
    plan.placements[id] = { bankId: `neo-bank-${bank}`, sectorIds: [`neo-bank-${bank}-sector-${sector}`], budgetKiB: 128 };
  }
  return plan;
}

