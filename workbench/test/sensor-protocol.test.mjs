test('commands survive driver reuse, layer versions and performance snapshots', () => {
  let p = newModuleProject();
  p = captureDriverHardware(p, p.catalog.activeDriverId);
  assert.deepEqual(motor(applyDriver(parseProject(serializeProject(p)), p.catalog.activeDriverId)), motor(p));
  const saved = saveLayerVersion(p, { layer: 'hardware', version: 'cmd-v1' });
  motor(saved)[0].frameBytes = 20;
  assert.equal(motor(applyLayerVersion(saved, 'hardware'))[0].frameBytes, 9);
  motor(p).push(Object.assign(createDriverCommand('status', 'status-read'), { periodUs: 100000 }));
  p = captureDriverHardware(p, p.catalog.activeDriverId);
  const reused = applyDriver(parseProject(serializeProject(p)), p.catalog.activeDriverId);
  assert.equal(motor(reused).length, 2); assert.equal(motor(reused)[1].purpose, 'status');
  const draft = createPerformanceDraft(p); draft.measuredAt = '2026-01-15'; draft.samples = [{ currentA: 1, torqueNm: 0.1, series: 'a' }];
  p = savePerformanceRecord(p, draft);
  const record = p.performance.records[0];
  Object.assign(record.snapshot.driver.hardware['hw-drivers'], { motorEncoderTransferMode: 'request_response', motorEncoderRequestHex: 'FF' });
  record.snapshot.layers.hardware.configuration['hw-drivers'].parameters.motorEncoderFrameBytes = 9;
  const loaded = parseProject(serializeProject(p));
  const shelf = loaded.performance.records[0].snapshot.driver.hardware['hw-drivers'], layerParameters = loaded.performance.records[0].snapshot.layers.hardware.configuration['hw-drivers'].parameters;
  assert.equal(Object.hasOwn(shelf, 'motorEncoderTransferMode'), false); assert.deepEqual(shelf.motorEncoderCommands, motor(p));
  assert.equal(Object.hasOwn(layerParameters, 'motorEncoderFrameBytes'), false); assert.deepEqual(layerParameters.motorEncoderCommands, motor(p));
});
