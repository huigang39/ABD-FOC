test('command shape rejects duplicate data, malformed hex, bounds and overflow', () => {
  checkDriverCommandShape([dataCommand()]);
  assert.throws(() => checkDriverCommandShape([dataCommand(), dataCommand({ id: 'second' })]), /最多一条主数据指令/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ requestHex: 'A 55' })]), /十六进制字节/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ headerHex: 'AA'.repeat(65) })]), /最多 64 字节/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ requestHex: 'AA'.repeat(33) })]), /最多 32 字节/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ frameBytes: 65 })]), /接收帧长/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ dataBits: 7 })]), /数值位宽/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ statusMask: 256 })]), /状态位掩码/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ valueScale: 'x' })]), /数值倍率/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ checksum: 'crc32' })]), /帧校验/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ id: 'dup' }), Object.assign(createDriverCommand('status', 'dup'))]), /唯一/);
  assert.throws(() => checkDriverCommandShape([dataCommand({ surplus: 1 })]), /未知字段/);
  const command = dataCommand(); delete command.statusExpected;
  assert.throws(() => checkDriverCommandShape([command]), /缺少字段/);
  assert.throws(() => checkDriverCommandShape(Array.from({ length: DRIVER_COMMANDS_MAX + 1 }, (_, index) => Object.assign(createDriverCommand(index ? 'other' : 'data'), { id: `c${index}` }))), /不超过 4 条/);
});
test('legacy flat protocol keys fold into one data command and the fold stays idempotent', () => {
  const p = newModuleProject();
  const flat = { motorEncoderTransferMode: 'active_upload', motorEncoderRequestHex: '01 03', motorEncoderStartHex: '12 34', motorEncoderStartupDelayUs: 1500, motorEncoderHeaderHex: 'AA 55', motorEncoderFooterHex: '', motorEncoderFrameBytes: 8, motorEncoderDataOffset: 2, motorEncoderDataType: 'unsigned', motorEncoderDataBits: 32, motorEncoderByteOrder: 'little', motorEncoderValueScale: 0.0001, motorEncoderValueOffset: 0, motorEncoderChecksum: 'crc16_modbus', motorEncoderChecksumStart: 0, motorEncoderStatusOffset: null, motorEncoderStatusMask: 0, motorEncoderStatusExpected: 0 };
  const parameters = structuredClone(params(p));
  for (const key of [...Object.keys(flat), 'motorEncoderCommands']) delete parameters[key];
  Object.assign(parameters, flat);
  migrateSensorParameters(parameters);
  const command = parameters.motorEncoderCommands.find(command => command.purpose === 'data');
  assert.equal(command.mode, 'active_upload'); assert.equal(command.requestHex, '12 34'); assert.equal(command.startupDelayUs, 1500);
  assert.equal(command.headerHex, 'AA 55'); assert.equal(command.frameBytes, 8); assert.equal(command.valueScale, 0.0001); assert.equal(command.checksum, 'crc16_modbus');
  for (const key of Object.keys(flat)) assert.equal(Object.hasOwn(parameters, key), false, key);
  const snapshot = structuredClone(parameters);
  migrateSensorParameters(parameters);
  assert.deepEqual(parameters, snapshot);
});
